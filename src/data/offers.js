const UNKNOWN_STATUS = Object.freeze({ id: 0, key: "unknown", label: "Unknown" })

const OFFER_STATUS_BY_ID = Object.freeze(
    OFFER_STATUSES.reduce((acc, status) => {
        acc[status.id] = status
        return acc
    }, {}),
)

const OFFER_STATUS_BY_LABEL = Object.freeze(
    OFFER_STATUSES.reduce((acc, status) => {
        acc[status.label.toLowerCase()] = status
        return acc
    }, {}),
)

