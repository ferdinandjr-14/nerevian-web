const buildOfferFormData = (offer) => ({
    ...createEmptyOfferForm(),
    commercialOfferId: `OFF-${offer.id}`,
    customer: offer.clientName,
    customerReference: offer.customerReference,
    salesRepresentative: offer.salesRepresentative,
    contactName: offer.contactName,
    groupByPartyType: offer.groupByPartyType,
    transportMode: TRANSPORT_LABELS[offer.tipusTransportId] || "",
    flow: FLOW_LABELS[offer.tipusFluxeId] || "",
    incoterm: INCOTERM_CODES[offer.incotermId] || "",
    portOrigin: offer.originLabel,
    portDestination: offer.destinationLabel,
    shippingLine: offer.shippingLineName,
    inlandCarrier: offer.inlandCarrierName || "",
    cargoType: CARGO_LABELS[offer.tipusCarregaId] || "",
    grossWeight: formatWeight(offer.pesBrut),
    createdDateStart: formatIsoDate(offer.dataCreacio),
    createdDateEnd: formatIsoDate(offer.dataCreacio),
    status: getOfferStatusLabel(offer.estatOfertaId),
    validityStart: formatIsoDate(offer.dataValidessaInicial),
    validityEnd: formatIsoDate(offer.dataValidessaFina),
    rejectReason: offer.raoRebuig || "",
    volume: formatVolume(offer.volum),
    profitCenter: offer.profitCenterLabel,
    comments: offer.comentaris || "",
})

