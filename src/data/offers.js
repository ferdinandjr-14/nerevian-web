const formatIsoDate = (isoDate) => {
    if (!isoDate) return ""
    const [year, month, day] = isoDate.split("-")
    if (!year || !month || !day) return ""
    return `${day}/${month}/${year}`
}

const formatWeight = (weight) => (weight == null ? "" : `${Number(weight).toLocaleString("en-US")} Kg`)
const formatVolume = (volume) => (volume == null ? "" : `${Number(volume).toLocaleString("en-US")} m3`)

export const getOfferStatus = (statusId) => OFFER_STATUS_BY_ID[Number(statusId)] || UNKNOWN_STATUS

export const getOfferStatusLabel = (statusId) => getOfferStatus(statusId).label

export const getOfferStatusByLabel = (statusLabel) => {
    if (typeof statusLabel !== "string") return UNKNOWN_STATUS
    return OFFER_STATUS_BY_LABEL[statusLabel.trim().toLowerCase()] || UNKNOWN_STATUS
}

